#!/usr/bin/env node
/**
 * Writes `src/types/supabase.ts` from the Supabase CLI (UTF-8).
 *
 * Usage (pick one source):
 *   npm run types:supabase              # uses --linked (supabase link in repo)
 *   SUPABASE_PROJECT_REF=<ref> npm run types:supabase:project
 *
 * Requires: npx supabase, and either a linked project or SUPABASE_PROJECT_REF.
 */

import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const outFile = resolve(root, "src/types/supabase.ts");

const projectRef = process.env.SUPABASE_PROJECT_REF?.trim();
const args = ["supabase", "gen", "types", "typescript", "--schema", "public"];

if (projectRef) {
  args.push("--project-id", projectRef);
} else {
  args.push("--linked");
}

const result = spawnSync("npx", args, {
  cwd: root,
  encoding: "utf8",
  maxBuffer: 16 * 1024 * 1024,
  shell: true,
});

if (result.error) {
  console.error(result.error);
  process.exit(1);
}

if (result.status !== 0) {
  console.error(result.stderr || result.stdout);
  process.exit(result.status ?? 1);
}

const banner = `/**
 * AUTO-GENERATED by scripts/gen-supabase-types.mjs — do not edit by hand.
 * Regenerate: npm run types:supabase
 *
 * Helpers (Tables, TablesInsert, …) live in src/types/supabase-helpers.ts.
 */

`;

const body = result.stdout?.trimStart() ?? "";
if (!body.includes("export type Database")) {
  console.error(
    "CLI output does not look like Supabase TypeScript types. Check login / project link."
  );
  process.exit(1);
}

writeFileSync(outFile, banner + body + "\n", "utf8");
console.log(`Wrote ${outFile}`);
